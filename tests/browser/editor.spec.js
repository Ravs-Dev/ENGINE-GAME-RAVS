import { test, expect } from '@playwright/test';
test('3D renderer, transforms, persistence and Play/Stop', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('#hierarchy button')).toHaveCount(3);
  await expect(page.locator('#inspector')).toContainText('Position');
  await expect(page.locator('#status')).not.toContainText('gagal');
  const rendered = await page.locator('canvas').evaluate(canvas => {
    const gl = canvas.getContext('webgl2'); return !!gl && gl.drawingBufferWidth > 0 && gl.getError() === gl.NO_ERROR;
  });
  expect(rendered).toBe(true);
  await page.locator('#sphere').click();
  await expect(page.locator('#hierarchy button')).toHaveCount(4);
  await page.locator('#inspector input').nth(1).fill('3');
  await page.locator('#inspector input').nth(1).dispatchEvent('change');
  await page.locator('#mode').selectOption('rotate');
  await page.locator('#mode').selectOption('scale');
  await page.locator('#mode').selectOption('translate');
  await page.getByRole('button', { name: 'Duplikat', exact: true }).click();
  await expect(page.locator('#hierarchy button')).toHaveCount(5);
  await page.getByRole('button', { name: 'Hapus', exact: true }).click();
  await expect(page.locator('#hierarchy button')).toHaveCount(4);
  await page.locator('#save').click();
  await page.reload();
  await expect(page.locator('#hierarchy button')).toHaveCount(4);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ravs.scene.3d.v2')));
  expect(saved.objects.at(-1).position.x).toBe(3);
  await page.locator('#hierarchy button').filter({ hasText: 'Player' }).click();
  await page.locator('#play').click();
  await expect(page.locator('#box')).toBeDisabled();
  await page.keyboard.down('d'); await page.waitForTimeout(300); await page.keyboard.up('d');
  await page.locator('#play').click();
  await expect(page.locator('#inspector input').nth(1)).toHaveValue('-2');
  const download = page.waitForEvent('download'); await page.locator('#export').click();
  expect((await download).suggestedFilename()).toBe('scene.ravs3d.json');
  await page.locator('#import').setInputFiles({ name: 'scene.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) });
  await expect(page.locator('#status')).toHaveText('Scene 3D berhasil diimpor.');
  await page.locator('#import').setInputFiles({ name: 'old.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') });
  await expect(page.locator('#status')).toContainText('Impor gagal');
  await expect(page.locator('#hierarchy button')).toHaveCount(4);
  await page.screenshot({ path: '/tmp/ravs-3d-editor.png' });
  expect(errors).toEqual([]);
});
